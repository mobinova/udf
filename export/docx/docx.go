// Package docx exports the normalized UDF document model to WordprocessingML.
package docx

import (
	"archive/zip"
	"bytes"
	"context"
	"fmt"
	"io"
	"math"
	"sort"
	"strings"

	word "github.com/mmonterroca/docxgo/v2"
	"github.com/mmonterroca/docxgo/v2/domain"
	model "github.com/mobinova/udf"
)

// Options controls handling of source details which the current document model
// or docxgo cannot represent.
type Options struct {
	AllowLossy bool
}

type Exporter struct{ Options Options }

func Export(ctx context.Context, doc *model.Document, dst io.Writer) (model.ExportReport, error) {
	return (Exporter{}).Export(ctx, doc, dst)
}

func ExportWithOptions(ctx context.Context, doc *model.Document, dst io.Writer, opts Options) (model.ExportReport, error) {
	return (Exporter{Options: opts}).Export(ctx, doc, dst)
}

func (e Exporter) Export(ctx context.Context, source *model.Document, dst io.Writer) (model.ExportReport, error) {
	state := &exportState{ctx: ctx, opts: e.Options, source: source, lists: make(map[string]int), resources: make(map[string]model.Resource), paragraphTabs: make(map[string][][]model.TabStop), currentPart: "word/document.xml"}
	if err := model.Validate(source); err != nil {
		return state.report(), err
	}
	if dst == nil {
		return state.report(), fmt.Errorf("docx export: nil writer")
	}
	for _, resource := range source.Resources {
		state.resources[resource.ID] = resource
	}
	state.defaultFont, state.defaultFontSize = defaultRunDefaults(source)
	if source.Signature.Present {
		state.add("signature.not_transferred", model.DiagnosticSignatureNotTransferred, "signature", "DOCX output is a derivative and does not transfer the source UDF signature")
	}
	state.add("layout.document_grid_inferred", model.DiagnosticVisualApproximation, "page", "A 360-twip document text grid was applied based on the supplied UYAP DOCX examples")
	for _, diagnostic := range source.Diagnostics {
		if isUnretainedSourceDetail(diagnostic.Code) {
			state.add("source.details_not_preserved", model.DiagnosticContentLoss, diagnostic.Location, "The normalized model does not retain all source XML details")
			break
		}
	}
	document := word.NewDocument()
	state.configureDocument(document)
	for i, block := range source.Body {
		if err := state.checkContext(); err != nil {
			return state.report(), err
		}
		if err := state.writeBlock(document, block, fmt.Sprintf("body[%d]", i)); err != nil {
			return state.report(), err
		}
	}
	if err := state.writeHeadersFooters(document); err != nil {
		return state.report(), err
	}
	if state.hasContentLoss && !e.Options.AllowLossy {
		return state.report(), model.ErrUnsupported
	}
	if err := contextError(ctx); err != nil {
		return state.report(), err
	}
	if err := document.Validate(); err != nil {
		return state.report(), fmt.Errorf("docx export: generated document failed validation: %w", err)
	}
	var generated bytes.Buffer
	if _, err := document.WriteTo(&generated); err != nil {
		return state.report(), fmt.Errorf("docx export: write failed: %w", err)
	}
	patched, err := state.patchWordPackage(generated.Bytes())
	if err != nil {
		return state.report(), fmt.Errorf("docx export: OOXML formatting: %w", err)
	}
	if _, err := dst.Write(patched); err != nil {
		return state.report(), fmt.Errorf("docx export: write failed: %w", err)
	}
	return state.report(), nil
}

type exportState struct {
	ctx                  context.Context
	opts                 Options
	source               *model.Document
	lists                map[string]int
	resources            map[string]model.Resource
	diagnostics          []model.Diagnostic
	hasContentLoss       bool
	defaultFont          string
	defaultFontSize      float64
	paragraphTabs        map[string][][]model.TabStop
	currentPart          string
	fontFallbackReported bool
	sizeFallbackReported bool
	indentationReported  bool
}

func (s *exportState) report() model.ExportReport {
	return model.ExportReport{Diagnostics: append([]model.Diagnostic(nil), s.diagnostics...)}
}

func (s *exportState) add(code string, class model.DiagnosticClass, location, message string) {
	if class == model.DiagnosticContentLoss {
		s.hasContentLoss = true
	}
	d := model.Diagnostic{Code: code, Severity: model.SeverityWarning, Class: class, Location: location, Message: message}
	if class == model.DiagnosticContentLoss {
		d.Severity = model.SeverityError
	}
	const maxDiagnostics = 512
	if len(s.diagnostics) < maxDiagnostics {
		s.diagnostics = append(s.diagnostics, d)
		return
	}
	s.diagnostics[maxDiagnostics-1] = model.Diagnostic{Code: "diagnostics.truncated", Severity: model.SeverityWarning, Class: model.DiagnosticNormalization, Location: "document", Message: "Additional export diagnostics were omitted by the limit"}
}

func (s *exportState) checkContext() error { return contextError(s.ctx) }

func (s *exportState) noteParagraph(tabs []model.TabStop) {
	s.paragraphTabs[s.currentPart] = append(s.paragraphTabs[s.currentPart], append([]model.TabStop(nil), tabs...))
}

// defaultRunDefaults uses the most frequently specified run font and size as
// the fallback for runs that inherit UDF document/style defaults. The examples
// show this is necessary: many UDF runs omit family/size while the resulting
// Word document still uses Times New Roman at 11 or 12 points.
func defaultRunDefaults(doc *model.Document) (string, float64) {
	fonts, sizes := map[string]int{}, map[float64]int{}
	var visit func([]model.Block)
	visit = func(blocks []model.Block) {
		for _, block := range blocks {
			switch block.Kind {
			case model.BlockParagraph:
				if block.Paragraph == nil {
					continue
				}
				for _, inline := range block.Paragraph.Inlines {
					var style model.TextStyle
					switch inline.Kind {
					case model.InlineRun:
						if inline.Run != nil {
							style = inline.Run.Style
						}
					case model.InlineField:
						if inline.Field != nil {
							style = inline.Field.Style
						}
					}
					if style.FontFamily != "" {
						fonts[style.FontFamily]++
					}
					if style.FontSize > 0 && finite(style.FontSize) {
						sizes[style.FontSize]++
					}
				}
			case model.BlockTable:
				if block.Table == nil {
					continue
				}
				for _, row := range block.Table.Rows {
					for _, cell := range row.Cells {
						visit(cell.Blocks)
					}
				}
			}
		}
	}
	visit(doc.Body)
	for _, header := range doc.Headers {
		visit(header.Blocks)
	}
	for _, footer := range doc.Footers {
		visit(footer.Blocks)
	}
	fontKeys := make([]string, 0, len(fonts))
	for key := range fonts {
		fontKeys = append(fontKeys, key)
	}
	sort.Strings(fontKeys)
	font := ""
	for _, key := range fontKeys {
		if font == "" || fonts[key] > fonts[font] {
			font = key
		}
	}
	sizeKeys := make([]float64, 0, len(sizes))
	for key := range sizes {
		sizeKeys = append(sizeKeys, key)
	}
	sort.Float64s(sizeKeys)
	var size float64
	for _, key := range sizeKeys {
		if size == 0 || sizes[key] > sizes[size] {
			size = key
		}
	}
	return font, size
}

func (s *exportState) patchWordPackage(data []byte) ([]byte, error) {
	reader, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, err
	}
	var output bytes.Buffer
	writer := zip.NewWriter(&output)
	for _, file := range reader.File {
		header := file.FileHeader
		entry, err := writer.CreateHeader(&header)
		if err != nil {
			return nil, err
		}
		r, err := file.Open()
		if err != nil {
			return nil, err
		}
		contents, readErr := io.ReadAll(r)
		closeErr := r.Close()
		if readErr != nil {
			return nil, readErr
		}
		if closeErr != nil {
			return nil, closeErr
		}
		if tabs, ok := s.paragraphTabs[file.Name]; ok {
			contents, err = patchParagraphTabs(contents, tabs)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", file.Name, err)
			}
		}
		if file.Name == "word/document.xml" {
			contents = addDocumentTextGrid(contents)
		}
		if _, err := entry.Write(contents); err != nil {
			return nil, err
		}
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

func patchParagraphTabs(data []byte, paragraphs [][]model.TabStop) ([]byte, error) {
	text := string(data)
	var out strings.Builder
	position, index := 0, 0
	for {
		start := strings.Index(text[position:], "<w:p>")
		if start < 0 {
			break
		}
		start += position
		end := strings.Index(text[start:], "</w:p>")
		if end < 0 {
			return nil, fmt.Errorf("malformed paragraph XML")
		}
		end += start + len("</w:p>")
		out.WriteString(text[position:start])
		paragraph := text[start:end]
		if index < len(paragraphs) && len(paragraphs[index]) > 0 {
			tabXML := make([]string, 0, len(paragraphs[index]))
			for _, stop := range paragraphs[index] {
				if stop.Position < 0 || !finite(stop.Position) {
					continue
				}
				align := map[string]string{"left": "left", "center": "center", "right": "right", "decimal": "decimal"}[strings.ToLower(stop.Alignment)]
				if align == "" {
					align = "left"
				}
				attrs := fmt.Sprintf(` w:val="%s" w:pos="%d"`, align, int(math.Round(stop.Position*20)))
				leader := map[string]string{"dot": "dot", "dash": "hyphen", "underscore": "underscore", "heavy": "heavy", "middot": "middleDot"}[strings.ToLower(stop.Leader)]
				if leader != "" {
					attrs += fmt.Sprintf(` w:leader="%s"`, leader)
				}
				tabXML = append(tabXML, "<w:tab"+attrs+"/>")
			}
			if len(tabXML) > 0 {
				insert := "<w:tabs>" + strings.Join(tabXML, "") + "</w:tabs>"
				if p := paragraphTabsInsertionPoint(paragraph); p >= 0 {
					paragraph = paragraph[:p] + insert + paragraph[p:]
				} else if p := strings.Index(paragraph, "<w:pPr>"); p >= 0 {
					paragraph = paragraph[:p+len("<w:pPr>")] + insert + paragraph[p+len("<w:pPr>"):]
				} else {
					paragraph = strings.Replace(paragraph, "<w:p>", "<w:p><w:pPr>"+insert+"</w:pPr>", 1)
				}
			}
		}
		paragraph = ensureZeroIndent(paragraph)
		out.WriteString(paragraph)
		position, index = end, index+1
	}
	out.WriteString(text[position:])
	for i := index; i < len(paragraphs); i++ {
		if len(paragraphs[i]) > 0 {
			return nil, fmt.Errorf("tab-stop paragraph mapping mismatch")
		}
	}
	return []byte(out.String()), nil
}

func paragraphTabsInsertionPoint(paragraph string) int {
	pPrStart := strings.Index(paragraph, "<w:pPr>")
	pPrEnd := strings.Index(paragraph, "</w:pPr>")
	if pPrStart < 0 || pPrEnd < 0 {
		return -1
	}
	anchors := []string{"<w:pBdr", "<w:shd", "<w:spacing", "<w:ind", "<w:jc", "<w:rPr", "</w:pPr>"}
	point := pPrEnd
	for _, anchor := range anchors {
		if i := strings.Index(paragraph[pPrStart:pPrEnd], anchor); i >= 0 && pPrStart+i < point {
			point = pPrStart + i
		}
	}
	// Numbering and paragraph styles precede tabs in the OOXML property order.
	for _, endTag := range []string{"</w:pStyle>", "</w:numPr>"} {
		if i := strings.Index(paragraph[pPrStart:point], endTag); i >= 0 {
			end := pPrStart + i + len(endTag)
			if end > point {
				point = end
			}
		}
	}
	return point
}

func ensureZeroIndent(paragraph string) string {
	if strings.Contains(paragraph, "<w:ind") {
		return paragraph
	}
	indent := `<w:ind w:left="0" w:right="0" w:firstLine="0"/>`
	if !strings.Contains(paragraph, "<w:pPr>") {
		return strings.Replace(paragraph, "<w:p>", "<w:p><w:pPr>"+indent+"</w:pPr>", 1)
	}
	point := strings.Index(paragraph, "</w:pPr>")
	if p := strings.Index(paragraph, "<w:jc"); p >= 0 && p < point {
		point = p
	}
	if spacingEnd := strings.Index(paragraph, "</w:spacing>"); spacingEnd >= 0 && spacingEnd < point {
		point = spacingEnd + len("</w:spacing>")
	}
	if tabsEnd := strings.Index(paragraph, "</w:tabs>"); tabsEnd >= 0 && tabsEnd < point && strings.Index(paragraph, "</w:spacing>") < 0 {
		point = tabsEnd + len("</w:tabs>")
	}
	if point < 0 {
		return paragraph
	}
	return paragraph[:point] + indent + paragraph[point:]
}

func addDocumentTextGrid(data []byte) []byte {
	text := string(data)
	const closing = "</w:sectPr>"
	if strings.Contains(text, "<w:docGrid") || !strings.Contains(text, closing) {
		return data
	}
	return []byte(strings.Replace(text, closing, `<w:docGrid w:linePitch="360"/>`+closing, 1))
}

func isUnretainedSourceDetail(code string) bool {
	switch code {
	case "source.unknown_element", "source.unknown_attribute", "source.template_data_unsupported", "table.row_spans_unresolved", "table.column_widths_unresolved", "layout.nested_header_footer":
		return true
	default:
		return false
	}
}

func (s *exportState) configureDocument(doc domain.Document) {
	section, err := doc.DefaultSection()
	if err == nil {
		page := s.source.Page
		if page.Width > 0 && page.Height > 0 && finite(page.Width) && finite(page.Height) {
			if err := section.SetPageSize(domain.PageSize{Width: pointsToTwips(page.Width), Height: pointsToTwips(page.Height)}); err != nil {
				s.add("layout.page_size_omitted", model.DiagnosticVisualApproximation, "page", "Page dimensions were not accepted by the DOCX backend")
			}
		} else if page.MediaSizeName == "" {
			s.add("layout.page_size_defaulted", model.DiagnosticVisualApproximation, "page", "Source page size is unknown; DOCX backend defaults are used")
		}
		if page.Orientation == model.Landscape {
			_ = section.SetOrientation(domain.OrientationLandscape)
		}
		if page.Orientation == model.Portrait {
			_ = section.SetOrientation(domain.OrientationPortrait)
		}
		margins := domain.Margins{Top: pointsToTwips(page.TopMargin), Right: pointsToTwips(page.RightMargin), Bottom: pointsToTwips(page.BottomMargin), Left: pointsToTwips(page.LeftMargin), Header: pointsToTwips(page.HeaderDistance), Footer: pointsToTwips(page.FooterDistance)}
		if page.LeftMargin != 0 || page.RightMargin != 0 || page.TopMargin != 0 || page.BottomMargin != 0 || page.HeaderDistance != 0 || page.FooterDistance != 0 {
			if err := section.SetMargins(margins); err != nil {
				s.add("layout.margins_omitted", model.DiagnosticVisualApproximation, "page", "Page margins were not accepted by the DOCX backend")
			}
		}
	} else {
		s.add("layout.section_unavailable", model.DiagnosticVisualApproximation, "page", "Document section layout could not be configured")
	}
	meta := &domain.Metadata{}
	for key, value := range s.source.Properties.Values {
		switch strings.ToLower(key) {
		case "title":
			meta.Title = value
		case "author", "creator":
			meta.Creator = value
		case "subject":
			meta.Subject = value
		default:
			s.add("metadata.udf_property_omitted", model.DiagnosticVisualApproximation, "properties", "UDF-specific property is not mapped to DOCX core metadata")
		}
	}
	if meta.Title != "" || meta.Creator != "" || meta.Subject != "" {
		_ = doc.SetMetadata(meta)
	}
	if s.source.WebID != "" {
		s.add("metadata.web_id_omitted", model.DiagnosticVisualApproximation, "webID", "UYAP web ID is not represented in DOCX metadata")
	}
}

func (s *exportState) writeBlock(doc domain.Document, block model.Block, location string) error {
	switch block.Kind {
	case model.BlockParagraph:
		p, err := doc.AddParagraph()
		if err != nil {
			return err
		}
		return s.writeParagraph(p, block.Paragraph, location)
	case model.BlockTable:
		return s.writeTable(doc, block.Table, location)
	case model.BlockPageBreak:
		return doc.AddPageBreak()
	case model.BlockUnknown:
		if block.Unknown == nil {
			return model.ErrInvalidModel
		}
		if block.Unknown.Text == "" {
			s.add("content.unknown_block_omitted", model.DiagnosticContentLoss, location, "Unknown block has no readable text")
			if !s.opts.AllowLossy {
				return model.ErrUnsupported
			}
			return nil
		}
		s.add("content.unknown_block_structure", model.DiagnosticVisualApproximation, location, "Unknown block was exported as a plain paragraph")
		p, err := doc.AddParagraph()
		if err != nil {
			return err
		}
		s.noteParagraph(nil)
		return s.addText(p, block.Unknown.Text, model.TextStyle{}, location)
	default:
		s.add("content.unknown_block_kind", model.DiagnosticContentLoss, location, "Unknown block kind cannot be represented")
		if s.opts.AllowLossy {
			return nil
		}
		return model.ErrUnsupported
	}
}

func (s *exportState) writeParagraph(p domain.Paragraph, source *model.Paragraph, location string) error {
	if source == nil {
		return model.ErrInvalidModel
	}
	props := source.Properties
	s.noteParagraph(props.Tabs)
	if props.Alignment != "" {
		if err := p.SetAlignment(docxAlignment(props.Alignment)); err != nil {
			s.add("paragraph.alignment_omitted", model.DiagnosticVisualApproximation, location, "Paragraph alignment was not accepted by the DOCX backend")
		}
	}
	if !s.indentationReported && (props.LeftIndent != 0 || props.RightIndent != 0 || props.FirstLineIndent != 0 || props.Hanging != 0) {
		s.add("paragraph.indentation_omitted", model.DiagnosticVisualApproximation, location, "UDF indent fields are not emitted until their units and Swing layout semantics are verified")
		s.indentationReported = true
	}
	if props.SpaceAbove != 0 {
		_ = p.SetSpacingBefore(pointsToTwips(props.SpaceAbove))
	}
	if props.SpaceBelow != 0 {
		_ = p.SetSpacingAfter(pointsToTwips(props.SpaceBelow))
	}
	if props.LineSpacing != 0 && finite(props.LineSpacing) && props.LineSpacing >= 0 && props.LineSpacing <= 10 {
		lineSpacing := domain.LineSpacing{Rule: domain.LineSpacingAuto, Value: int(math.Round((1 + props.LineSpacing) * 240))}
		if err := p.SetLineSpacing(lineSpacing); err != nil {
			s.add("paragraph.line_spacing_omitted", model.DiagnosticVisualApproximation, location, "UDF line-spacing setting was not accepted by the DOCX backend")
		}
	} else if props.LineSpacing != 0 {
		s.add("paragraph.line_spacing_omitted", model.DiagnosticVisualApproximation, location, "UDF line-spacing value was outside the supported range")
	}
	if source.StyleName != "" {
		if style, ok := docxStyleName(source.StyleName); ok {
			if err := p.SetStyle(style); err != nil {
				s.add("paragraph.style_reference_omitted", model.DiagnosticVisualApproximation, location, "Source paragraph style has no matching DOCX built-in style")
			}
		} else if !isDefaultUDFStyle(source.StyleName) {
			s.add("paragraph.style_reference_omitted", model.DiagnosticVisualApproximation, location, "Source style name was not mapped to a DOCX built-in style")
		}
	}
	if props.Numbered || props.Bulleted {
		if err := s.writeListMarker(p, props, location); err != nil {
			return err
		}
	}
	for i, in := range source.Inlines {
		if err := s.checkContext(); err != nil {
			return err
		}
		if err := s.writeInline(p, in, fmt.Sprintf("%s.inlines[%d]", location, i)); err != nil {
			return err
		}
	}
	return nil
}

func (s *exportState) writeListMarker(p domain.Paragraph, props model.ParagraphStyle, location string) error {
	marker := ""
	key := fmt.Sprintf("%s:%d", props.ListID, props.ListLevel)
	if props.Numbered {
		s.lists[key]++
		marker = listMarker(props.NumberType, s.lists[key])
	} else {
		marker = bulletMarker(props.BulletType)
	}
	if marker == "" {
		s.add("list.marker_omitted", model.DiagnosticVisualApproximation, location, "List marker type was not recognized")
		return nil
	}
	s.add("list.numbering_as_text", model.DiagnosticVisualApproximation, location, "List marker was written as text because the DOCX backend does not expose numbering-definition creation")
	run, err := p.AddRun()
	if err != nil {
		return err
	}
	return run.SetText(marker)
}

func listMarker(kind string, n int) string {
	switch kind {
	case "NUMBER_TYPE_NUMBER_PARENTHESIS":
		return fmt.Sprintf("%d) ", n)
	case "NUMBER_TYPE_CHAR_SMALL_DOT":
		return fmt.Sprintf("%s. ", alphaNumber(n, false))
	case "NUMBER_TYPE_CHAR_SMALL_PARENTHESIS":
		return fmt.Sprintf("%s) ", alphaNumber(n, false))
	case "NUMBER_TYPE_CHAR_BIG_DOT":
		return fmt.Sprintf("%s. ", alphaNumber(n, true))
	case "NUMBER_TYPE_CHAR_BIG_PARENTHESIS":
		return fmt.Sprintf("%s) ", alphaNumber(n, true))
	case "NUMBER_TYPE_ROMAN_SMALL_DOT":
		return fmt.Sprintf("%s. ", romanNumber(n, false))
	case "NUMBER_TYPE_ROMAN_SMALL_PARENTHESIS":
		return fmt.Sprintf("%s) ", romanNumber(n, false))
	case "NUMBER_TYPE_ROMAN_BIG_DOT":
		return fmt.Sprintf("%s. ", romanNumber(n, true))
	case "NUMBER_TYPE_ROMAN_BIG_PARENTHESIS":
		return fmt.Sprintf("%s) ", romanNumber(n, true))
	default:
		return fmt.Sprintf("%d. ", n)
	}
}

func bulletMarker(kind string) string {
	switch kind {
	case "BULLET_TYPE_RECTANGLE":
		return "■ "
	case "BULLET_TYPE_ARROW":
		return "➤ "
	case "BULLET_TYPE_DIAMOND":
		return "◆ "
	case "BULLET_TYPE_DIAMOND_2":
		return "◊ "
	case "BULLET_TYPE_TRIANGLE":
		return "▲ "
	case "BULLET_TYPE_RECTANGLE_D":
		return "□ "
	default:
		return "• "
	}
}

func alphaNumber(n int, upper bool) string {
	if n < 1 {
		n = 1
	}
	var out []byte
	for n > 0 {
		n--
		out = append(out, byte('a'+n%26))
		n /= 26
	}
	for i, j := 0, len(out)-1; i < j; i, j = i+1, j-1 {
		out[i], out[j] = out[j], out[i]
	}
	if upper {
		for i := range out {
			out[i] -= 'a' - 'A'
		}
	}
	return string(out)
}

func romanNumber(n int, upper bool) string {
	if n < 1 {
		n = 1
	}
	values := []struct {
		value  int
		symbol string
	}{{1000, "M"}, {900, "CM"}, {500, "D"}, {400, "CD"}, {100, "C"}, {90, "XC"}, {50, "L"}, {40, "XL"}, {10, "X"}, {9, "IX"}, {5, "V"}, {4, "IV"}, {1, "I"}}
	var b strings.Builder
	for _, v := range values {
		for n >= v.value {
			b.WriteString(v.symbol)
			n -= v.value
		}
	}
	result := b.String()
	if !upper {
		return strings.ToLower(result)
	}
	return result
}

func (s *exportState) writeInline(p domain.Paragraph, in model.Inline, location string) error {
	switch in.Kind {
	case model.InlineRun:
		if in.Run == nil {
			return nil
		}
		return s.addText(p, in.Run.Text, in.Run.Style, location)
	case model.InlineField:
		if in.Field == nil {
			return nil
		}
		s.add("field.cached_value_only", model.DiagnosticVisualApproximation, location, "Field was exported with its cached visible value")
		return s.addText(p, in.Field.Text, in.Field.Style, location)
	case model.InlineTab:
		if in.Tab == nil {
			return nil
		}
		if err := s.addText(p, in.Tab.Text, model.TextStyle{}, location); err != nil {
			return err
		}
		return nil
	case model.InlineBreak:
		if in.Break == nil {
			return nil
		}
		run, err := p.AddRun()
		if err != nil {
			return err
		}
		return run.AddBreak(domain.BreakTypeLine)
	case model.InlineImage:
		if in.Image == nil {
			return model.ErrInvalidModel
		}
		resource, ok := s.resources[in.Image.ResourceID]
		if !ok {
			s.add("resource.image_omitted", model.DiagnosticContentLoss, location, "Image resource is unavailable")
			if s.opts.AllowLossy {
				return nil
			}
			return model.ErrUnsupported
		}
		format, ok := imageFormat(resource.MediaType)
		if !ok {
			s.add("resource.image_format_omitted", model.DiagnosticContentLoss, location, "Image format is not supported by the DOCX backend")
			if s.opts.AllowLossy {
				return nil
			}
			return model.ErrUnsupported
		}
		size := domain.NewImageSizeInches(in.Image.Width/72, in.Image.Height/72)
		if _, err := p.AddImageFromBytesWithSize(resource.Data, format, size); err != nil {
			s.add("resource.image_export_failed", model.DiagnosticContentLoss, location, "Image could not be inserted into DOCX")
			return err
		}
		return nil
	case model.InlineUnknown:
		if in.Unknown == nil {
			return model.ErrInvalidModel
		}
		if in.Unknown.Text == "" {
			s.add("content.unknown_inline_omitted", model.DiagnosticContentLoss, location, "Unknown inline item has no readable text")
			if s.opts.AllowLossy {
				return nil
			}
			return model.ErrUnsupported
		}
		s.add("content.unknown_inline_structure", model.DiagnosticVisualApproximation, location, "Unknown inline item was exported as text")
		return s.addText(p, in.Unknown.Text, model.TextStyle{}, location)
	default:
		s.add("content.unknown_inline_kind", model.DiagnosticContentLoss, location, "Unknown inline kind cannot be represented")
		if s.opts.AllowLossy {
			return nil
		}
		return model.ErrUnsupported
	}
}

func (s *exportState) addText(p domain.Paragraph, text string, style model.TextStyle, location string) error {
	run, err := p.AddRun()
	if err != nil {
		return err
	}
	if err = run.SetText(text); err != nil {
		return err
	}
	font := style.FontFamily
	if font == "" {
		font = s.defaultFont
		if font != "" && !s.fontFallbackReported {
			s.add("style.font_default_inferred", model.DiagnosticVisualApproximation, location, "Missing run font was inferred from the most common explicit source font")
			s.fontFallbackReported = true
		}
	}
	if font != "" {
		if err = run.SetFont(domain.Font{Name: font}); err != nil {
			s.add("style.font_omitted", model.DiagnosticVisualApproximation, location, "Font family was not accepted by DOCX backend")
		}
	}
	size := style.FontSize
	if size <= 0 {
		size = s.defaultFontSize
		if size > 0 && !s.sizeFallbackReported {
			s.add("style.font_size_default_inferred", model.DiagnosticVisualApproximation, location, "Missing run size was inferred from the most common explicit source size")
			s.sizeFallbackReported = true
		}
	}
	if size > 0 {
		half := int(math.Round(size * 2))
		if err = run.SetSize(half); err != nil {
			s.add("style.font_size_omitted", model.DiagnosticVisualApproximation, location, "Font size was not accepted by DOCX backend")
		}
		if math.Abs(float64(half)/2-size) > 0.001 {
			s.add("style.font_size_rounded", model.DiagnosticVisualApproximation, location, "DOCX font size was rounded to half-point precision")
		}
	}
	if err = run.SetBold(style.Bold); err != nil {
		return err
	}
	if err = run.SetItalic(style.Italic); err != nil {
		return err
	}
	if err = run.SetStrike(style.Strike); err != nil {
		return err
	}
	underline := domain.UnderlineNone
	if style.Underline {
		underline = domain.UnderlineSingle
	}
	if err = run.SetUnderline(underline); err != nil {
		return err
	}
	if style.Foreground.Set {
		if err = run.SetColor(colorFromARGB(style.Foreground.Val)); err != nil {
			s.add("style.color_omitted", model.DiagnosticVisualApproximation, location, "Run color was not accepted by DOCX backend")
		}
	}
	if style.Background.Set {
		s.add("style.background_omitted", model.DiagnosticVisualApproximation, location, "Run background color cannot be represented by the DOCX run API")
	}
	return nil
}

func (s *exportState) writeTable(doc domain.Document, source *model.Table, location string) error {
	if source == nil {
		return model.ErrInvalidModel
	}
	rows := len(source.Rows)
	cols := source.ColumnCount
	if rows == 0 || cols == 0 {
		s.add("table.empty_omitted", model.DiagnosticVisualApproximation, location, "Empty table was omitted")
		return nil
	}
	table, err := doc.AddTable(rows, cols)
	if err != nil {
		s.add("table.create_failed", model.DiagnosticContentLoss, location, "Table dimensions were not accepted by DOCX backend")
		return err
	}
	s.applyTableWidths(table, source, location)
	var merges []mergeRequest
	for ri, row := range source.Rows {
		if err := s.checkContext(); err != nil {
			return err
		}
		r, _ := table.Row(ri)
		if row.Height > 0 {
			_ = r.SetHeight(pointsToTwips(row.Height))
		}
		if row.Type == "headerRow" {
			_ = r.SetRepeatAsHeader(true)
		}
		for ci, cell := range row.Cells {
			if cell.GridCol < 0 || cell.GridCol >= cols {
				continue
			}
			target, cellErr := r.Cell(cell.GridCol)
			if cellErr != nil {
				return cellErr
			}
			if err := s.writeCell(target, cell, fmt.Sprintf("%s.rows[%d].cells[%d]", location, ri, ci)); err != nil {
				return err
			}
			if cell.RowSpan > 1 || cell.ColSpan > 1 {
				merges = append(merges, mergeRequest{row: ri, col: cell.GridCol, rows: cell.RowSpan, cols: cell.ColSpan, location: fmt.Sprintf("%s.rows[%d].cells[%d]", location, ri, ci)})
			}
		}
	}
	for _, merge := range merges {
		r, _ := table.Row(merge.row)
		cell, _ := r.Cell(merge.col)
		if err := cell.Merge(merge.cols, merge.rows); err != nil {
			s.add("table.span_omitted", model.DiagnosticContentLoss, merge.location, "Table merge span was not accepted by DOCX backend")
			if !s.opts.AllowLossy {
				return err
			}
		}
	}
	return nil
}

func (s *exportState) applyTableWidths(table domain.Table, source *model.Table, location string) {
	columns := source.ColumnCount
	if columns <= 0 {
		return
	}
	available := s.source.Page.Width - s.source.Page.LeftMargin - s.source.Page.RightMargin
	if !finite(available) || available <= 0 {
		available = 0
	}
	total := available
	allPoints := len(source.ColumnWidths) == columns
	pointTotal := 0.0
	for _, width := range source.ColumnWidths {
		if width.Unit != model.UnitPoint || !finite(width.Value) || width.Value <= 0 {
			allPoints = false
			break
		}
		pointTotal += width.Value
	}
	if allPoints && pointTotal > 0 {
		total = pointTotal
	}
	if total <= 0 {
		s.add("table.width_unresolved", model.DiagnosticVisualApproximation, location, "Table width could not be inferred because page width is unknown")
		return
	}
	if err := table.SetWidth(domain.TableWidth{Type: domain.WidthDXA, Value: pointsToTwips(total)}); err != nil {
		s.add("table.width_omitted", model.DiagnosticVisualApproximation, location, "Table width was not accepted by DOCX backend")
	}
	widths := make([]float64, columns)
	remaining, autoCount := total, 0
	for i := range widths {
		if i >= len(source.ColumnWidths) {
			autoCount++
			continue
		}
		width := source.ColumnWidths[i]
		switch width.Unit {
		case model.UnitPoint:
			if finite(width.Value) && width.Value > 0 {
				widths[i] = width.Value
				remaining -= width.Value
			} else {
				autoCount++
			}
		case model.UnitPercent:
			if finite(width.Value) && width.Value > 0 {
				widths[i] = total * width.Value / 100
				remaining -= widths[i]
			} else {
				autoCount++
			}
		default:
			autoCount++
		}
	}
	if autoCount > 0 {
		share := remaining / float64(autoCount)
		for i := range widths {
			if widths[i] == 0 {
				widths[i] = share
			}
		}
	}
	sum := 0.0
	for _, width := range widths {
		sum += width
	}
	if sum > 0 && math.Abs(sum-total) > 0.01 {
		for i := range widths {
			widths[i] *= total / sum
		}
	}
	for _, row := range source.Rows {
		for _, cell := range row.Cells {
			if cell.GridCol < 0 || cell.GridCol >= len(widths) || cell.GridRow < 0 || cell.GridRow >= len(source.Rows) {
				continue
			}
			r, err := table.Row(cell.GridRow)
			if err != nil {
				continue
			}
			c, err := r.Cell(cell.GridCol)
			if err != nil {
				continue
			}
			if err := c.SetWidth(pointsToTwips(widths[cell.GridCol])); err != nil {
				s.add("table.column_width_omitted", model.DiagnosticVisualApproximation, location, "A table column width was not accepted by DOCX backend")
			}
		}
	}
}

type mergeRequest struct {
	row, col, rows, cols int
	location             string
}

func (s *exportState) writeCell(target domain.TableCell, source model.TableCell, location string) error {
	if source.Background.Set {
		if err := target.SetShading(colorFromARGB(source.Background.Val)); err != nil {
			s.add("table.cell_shading_omitted", model.DiagnosticVisualApproximation, location, "Cell shading was not accepted by DOCX backend")
		}
	}
	if align, ok := verticalAlignment(source.VerticalAlign); ok {
		if err := target.SetVerticalAlignment(align); err != nil {
			s.add("table.cell_alignment_omitted", model.DiagnosticVisualApproximation, location, "Cell vertical alignment was not accepted by DOCX backend")
		}
	} else if source.VerticalAlign != "" {
		s.add("table.cell_alignment_omitted", model.DiagnosticVisualApproximation, location, "Cell vertical alignment was not recognized")
	}
	if source.Border.Width > 0 || source.Border.Kind != "" {
		border := makeBorder(source.Border)
		borders := domain.TableBorders{Top: border, Right: border, Bottom: border, Left: border}
		if source.Border.Spec != 0 {
			if source.Border.Spec&1 == 0 {
				borders.Top = domain.BorderStyle{}
			}
			if source.Border.Spec&2 == 0 {
				borders.Right = domain.BorderStyle{}
			}
			if source.Border.Spec&4 == 0 {
				borders.Bottom = domain.BorderStyle{}
			}
			if source.Border.Spec&8 == 0 {
				borders.Left = domain.BorderStyle{}
			}
		}
		if source.Border.Kind == "borderNone" {
			borders = domain.TableBorders{}
		}
		if err := target.SetBorders(borders); err != nil {
			s.add("table.cell_border_omitted", model.DiagnosticVisualApproximation, location, "Cell borders were not accepted by DOCX backend")
		}
	}
	for i, block := range source.Blocks {
		if err := s.checkContext(); err != nil {
			return err
		}
		switch block.Kind {
		case model.BlockParagraph:
			p, err := target.AddParagraph()
			if err != nil {
				return err
			}
			if err := s.writeParagraph(p, block.Paragraph, fmt.Sprintf("%s.blocks[%d]", location, i)); err != nil {
				return err
			}
		case model.BlockTable:
			nested, err := target.AddTable(len(block.Table.Rows), block.Table.ColumnCount)
			if err != nil {
				return err
			}
			if err := s.fillExistingTable(nested, block.Table, fmt.Sprintf("%s.blocks[%d]", location, i)); err != nil {
				return err
			}
		default:
			s.add("table.cell_block_omitted", model.DiagnosticContentLoss, location, "Unsupported table-cell block was omitted")
			if !s.opts.AllowLossy {
				return model.ErrUnsupported
			}
		}
	}
	return nil
}

func (s *exportState) fillExistingTable(table domain.Table, source *model.Table, location string) error {
	s.applyTableWidths(table, source, location)
	var merges []mergeRequest
	for ri, row := range source.Rows {
		target, _ := table.Row(ri)
		if row.Height > 0 {
			_ = target.SetHeight(pointsToTwips(row.Height))
		}
		for ci, cell := range row.Cells {
			if cell.GridCol < 0 || cell.GridCol >= table.ColumnCount() {
				continue
			}
			targetCell, err := target.Cell(cell.GridCol)
			if err != nil {
				return err
			}
			if err := s.writeCell(targetCell, cell, fmt.Sprintf("%s.rows[%d].cells[%d]", location, ri, ci)); err != nil {
				return err
			}
			if cell.RowSpan > 1 || cell.ColSpan > 1 {
				merges = append(merges, mergeRequest{row: ri, col: cell.GridCol, rows: cell.RowSpan, cols: cell.ColSpan, location: location})
			}
		}
	}
	for _, m := range merges {
		r, _ := table.Row(m.row)
		c, _ := r.Cell(m.col)
		if err := c.Merge(m.cols, m.rows); err != nil {
			s.add("table.span_omitted", model.DiagnosticContentLoss, m.location, "Nested table merge was not accepted by DOCX backend")
			if !s.opts.AllowLossy {
				return err
			}
		}
	}
	return nil
}

func (s *exportState) writeHeadersFooters(doc domain.Document) error {
	section, err := doc.DefaultSection()
	if err != nil {
		return err
	}
	for i, header := range s.source.Headers {
		s.currentPart = fmt.Sprintf("word/header%d.xml", i+1)
		target, err := section.Header(domain.HeaderDefault)
		if err != nil {
			return err
		}
		if header.StartPage > 1 {
			s.add("header.start_page_omitted", model.DiagnosticVisualApproximation, fmt.Sprintf("headers[%d]", i), "Header start-page behavior is not represented")
		}
		if err := s.writeHeaderFooterBlocks(target, header.Blocks, fmt.Sprintf("headers[%d]", i)); err != nil {
			return err
		}
	}
	for i, footer := range s.source.Footers {
		s.currentPart = fmt.Sprintf("word/footer%d.xml", i+1)
		target, err := section.Footer(domain.FooterDefault)
		if err != nil {
			return err
		}
		if footer.StartPage > 1 {
			s.add("footer.start_page_omitted", model.DiagnosticVisualApproximation, fmt.Sprintf("footers[%d]", i), "Footer start-page behavior is not represented")
		}
		if err := s.writeHeaderFooterBlocks(target, footer.Blocks, fmt.Sprintf("footers[%d]", i)); err != nil {
			return err
		}
	}
	return nil
}

type headerFooterBlocks interface {
	AddParagraph() (domain.Paragraph, error)
	AddTable(rows, cols int) (domain.Table, error)
}

func (s *exportState) writeHeaderFooterBlocks(target headerFooterBlocks, blocks []model.Block, location string) error {
	for i, block := range blocks {
		loc := fmt.Sprintf("%s.blocks[%d]", location, i)
		switch block.Kind {
		case model.BlockParagraph:
			p, err := target.AddParagraph()
			if err != nil {
				return err
			}
			if err := s.writeParagraph(p, block.Paragraph, loc); err != nil {
				return err
			}
		case model.BlockTable:
			t, err := target.AddTable(len(block.Table.Rows), block.Table.ColumnCount)
			if err != nil {
				return err
			}
			if err := s.fillExistingTable(t, block.Table, loc); err != nil {
				return err
			}
		default:
			s.add("header_footer.block_omitted", model.DiagnosticContentLoss, loc, "Unsupported header/footer block was omitted")
			if !s.opts.AllowLossy {
				return model.ErrUnsupported
			}
		}
	}
	return nil
}

func docxAlignment(a model.Alignment) domain.Alignment {
	switch a {
	case model.AlignCenter:
		return domain.AlignmentCenter
	case model.AlignRight:
		return domain.AlignmentRight
	case model.AlignJustify:
		return domain.AlignmentJustify
	default:
		return domain.AlignmentLeft
	}
}
func verticalAlignment(a string) (domain.VerticalAlignment, bool) {
	switch a {
	case "top":
		return domain.VerticalAlignTop, true
	case "vcenter":
		return domain.VerticalAlignCenter, true
	case "bottom":
		return domain.VerticalAlignBottom, true
	case "":
		return domain.VerticalAlignTop, false
	default:
		return domain.VerticalAlignTop, false
	}
}
func imageFormat(media string) (domain.ImageFormat, bool) {
	switch strings.ToLower(strings.TrimSpace(strings.Split(media, ";")[0])) {
	case "image/png":
		return domain.ImageFormatPNG, true
	case "image/jpeg":
		return domain.ImageFormatJPEG, true
	case "image/gif":
		return domain.ImageFormatGIF, true
	case "image/bmp":
		return domain.ImageFormatBMP, true
	case "image/tiff":
		return domain.ImageFormatTIFF, true
	case "image/webp":
		return domain.ImageFormatWEBP, true
	case "image/svg+xml":
		return domain.ImageFormatSVG, true
	}
	return "", false
}
func colorFromARGB(value int32) domain.Color {
	v := uint32(value)
	return domain.Color{R: uint8(v >> 16), G: uint8(v >> 8), B: uint8(v)}
}
func makeBorder(source model.Border) domain.BorderStyle {
	style := domain.BorderSingle
	switch source.Style {
	case "borderStyle-dotted":
		style = domain.BorderDotted
	case "borderStyle-dashed":
		style = domain.BorderDashed
	case "borderStyle-double":
		style = domain.BorderDouble
	}
	return domain.BorderStyle{Style: style, Width: int(math.Round(source.Width * 8)), Color: colorFromARGB(source.Color.Val)}
}
func docxStyleName(name string) (string, bool) {
	switch strings.ToLower(strings.ReplaceAll(name, " ", "")) {
	case "heading1", "heading2", "heading3", "heading4", "heading5", "heading6", "heading7", "heading8", "heading9":
		return strings.Title(strings.ToLower(name)), true
	}
	return "", false
}
func isDefaultUDFStyle(name string) bool {
	switch strings.ToLower(strings.ReplaceAll(name, " ", "")) {
	case "", "default", "normal", "hvl-default", "body":
		return true
	default:
		return false
	}
}
func pointsToTwips(value float64) int { return int(math.Round(value * 20)) }
func finite(value float64) bool       { return !math.IsNaN(value) && !math.IsInf(value, 0) }
func contextError(ctx context.Context) error {
	if ctx == nil {
		return nil
	}
	select {
	case <-ctx.Done():
		return ctx.Err()
	default:
		return nil
	}
}
